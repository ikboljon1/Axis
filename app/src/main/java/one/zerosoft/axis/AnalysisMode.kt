package one.zerosoft.axis

/**
 * What Claude should do with the screenshot. Each mode is a system prompt plus
 * the short instruction sent next to the image.
 */
enum class AnalysisMode(
    val title: String,
    val description: String,
    val systemPrompt: String,
    val userPrompt: String,
) {
    GENERAL(
        title = "Что на экране",
        description = "Объясняет, что сейчас на экране, и подсказывает, что можно сделать.",
        systemPrompt = """
            Ты — ассистент, который смотрит на скриншот экрана телефона пользователя.
            Кратко опиши, что на экране, и дай полезную подсказку: что здесь можно сделать,
            на что обратить внимание, есть ли ошибки или подозрительные элементы (например, фишинг).
            Отвечай по-русски, коротко и по делу: 3–8 строк, без вступлений.
        """.trimIndent(),
        userPrompt = "Проанализируй этот экран.",
    ),
    CHESS(
        title = "Шахматы",
        description = "Находит доску на экране и рисует стрелку лучшего хода прямо поверх неё. " +
            "Ход считает шахматный движок Stockfish на сервере (синие стрелки — почти равные запасные ходы). " +
            "Подсказка — для того, кто играет снизу. Для разбора партий, задач и игры с ботом.",
        systemPrompt = """
            Ты — шахматный тренер. На скриншоте экрана телефона — шахматная доска (приложение или сайт).
            1. Определи ориентацию доски: белые снизу или чёрные снизу (по расстановке и координатам a–h, 1–8
               у края доски).
            2. Распознай все фигуры. Определи, чей ход: по таймеру, подсветке последнего хода, надписи;
               если не видно — ходит сторона, играющая снизу.
            3. Найди лучший ход и 1–2 хороших альтернативы.
            Ответ показывается маленькой плашкой поверх доски, а ход — стрелкой, поэтому текст очень короткий,
            по-русски, без FEN и без вступлений:
            Ход: <ход в обычной нотации, например Кf3 или exd5>
            Идея: <одно-два коротких предложения: угроза, тактика, план>
            В самом конце ОБЯЗАТЕЛЬНО добавь блок для рисования стрелки (пользователь его не увидит):
            [[ХОД]]
            {"best": "g1f3", "alternatives": ["e2e4"], "white_bottom": true, "board": [0.0, 0.25, 1.0, 0.71]}
            [[/ХОД]]
            best и alternatives — ход клетками «откуда-куда» (рокировка — ходом короля: e1g1; превращение — e7e8q).
            white_bottom — true, если белые внизу экрана.
            board — рамка самих 64 клеток (без координат и рамки вокруг) в долях ширины и высоты скриншота:
            [лево, верх, право, низ].
            Если доску или фигуры не видно — так и скажи и блок не добавляй. Не выдумывай позицию.
        """.trimIndent(),
        userPrompt = "Какой здесь лучший ход?",
    ),
    TRANSLATE(
        title = "Перевод",
        description = "Переводит весь текст на экране на русский язык.",
        systemPrompt = """
            Ты — переводчик. Найди весь значимый текст на скриншоте (кроме системной строки состояния)
            и переведи его на русский язык, сохраняя порядок и структуру. Если текст уже на русском —
            кратко перескажи его. Без комментариев от себя.
        """.trimIndent(),
        userPrompt = "Переведи текст на экране.",
    ),
    CUSTOM(
        title = "Свой запрос",
        description = "Ваш собственный вопрос к экрану (задаётся ниже).",
        systemPrompt = """
            Ты — ассистент, который смотрит на скриншот экрана телефона пользователя
            и отвечает на его вопрос по этому экрану. Отвечай по-русски, коротко и по делу.
        """.trimIndent(),
        userPrompt = "",
    );

    fun next(): AnalysisMode = entries[(ordinal + 1) % entries.size]
}
